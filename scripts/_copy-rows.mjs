import { readFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('./copy-sources.json', import.meta.url), 'utf8'));
export const rows = [];

function add(en, hi, bn, te) {
  if (!src.includes(en)) throw new Error('not in source: ' + JSON.stringify(en).slice(0, 140));
  rows.push([en, hi, bn, te]);
}

function addP(prefix, hi, bn, te) {
  const hits = src.filter((s) => s.startsWith(prefix));
  if (hits.length !== 1) {
    throw new Error('prefix ' + JSON.stringify(prefix) + ' -> ' + hits.length + '\n' + hits.map((h) => h.slice(0, 70)).join('\n'));
  }
  rows.push([hits[0], hi, bn, te]);
}

