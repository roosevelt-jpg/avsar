import { readdirSync, writeFileSync } from 'node:fs';
import { keys, rows as malayalamRows } from './_emit-copy.mjs';
import { triples as marathiRows } from './_gen-copy.mjs';
import { rows as hindiRows } from './_copy-rows.mjs';

/**
 * Writes src/lib/cms/copy/<locale>.ts from the translation tables in the
 * underscore scripts. A language with no table yet gets an empty map, which
 * the site renders as English. Run `node scripts/emit-content-copy.mjs`.
 */

const LOCALES = ['hi', 'bn', 'mr', 'te', 'ta', 'ur', 'gu', 'kn', 'or', 'ml', 'pa', 'as', 'ar'];
const maps = Object.fromEntries(LOCALES.map((code) => [code, {}]));

const known = new Set(keys);

// Codes such as A2 and B1 are excluded from translation and stay as written.
for (const [en, hi, bn, te] of hindiRows.filter(([en]) => known.has(en))) {
  maps.hi[en] = hi;
  maps.bn[en] = bn;
  maps.te[en] = te;
}
// These two tables are positional: row i translates keys[i].
malayalamRows.forEach(([ml, ta, ur], i) => {
  maps.ml[keys[i]] = ml;
  maps.ta[keys[i]] = ta;
  maps.ur[keys[i]] = ur;
});
marathiRows.forEach(([mr, gu, kn], i) => {
  maps.mr[keys[i]] = mr;
  maps.gu[keys[i]] = gu;
  maps.kn[keys[i]] = kn;
});

// Keyed tables in scripts/copy-tables/, applied in file-name order.
const tableDir = new URL('./copy-tables/', import.meta.url);
for (const name of readdirSync(tableDir).filter((n) => n.endsWith('.mjs') && n !== 'table.mjs').sort()) {
  const { default: byLocale } = await import(new URL(name, tableDir));
  for (const [code, map] of Object.entries(byLocale)) Object.assign(maps[code], map);
}

const tokens = (s) => (s.match(/\{\{[a-z0-9_]+\}\}/g) ?? []).sort().join('|');
const links = (s) => [...s.matchAll(/\]\(([^)]+)\)/g)].map((m) => m[1]).join('|');
const bold = (s) => (s.match(/\*\*/g) ?? []).length;
const digits = (s) => (s.match(/\d+/g) ?? []).sort().join('|');

// Unicode block of each locale's own script. A letter from another Indic or
// Arabic block inside a translation is a typing slip that a reader would see
// as a broken glyph. The danda (U+0964/5) is shared by several scripts.
const scriptBlock = {
  hi: [0x0900, 0x097f], mr: [0x0900, 0x097f], bn: [0x0980, 0x09ff], as: [0x0980, 0x09ff],
  pa: [0x0a00, 0x0a7f], gu: [0x0a80, 0x0aff], or: [0x0b00, 0x0b7f], ta: [0x0b80, 0x0bff],
  te: [0x0c00, 0x0c7f], kn: [0x0c80, 0x0cff], ml: [0x0d00, 0x0d7f], ur: [0x0600, 0x06ff], ar: [0x0600, 0x06ff],
};
const foreignScript = (code, s) => {
  const [lo, hi] = scriptBlock[code];
  return [...s].some((ch) => {
    const cp = ch.codePointAt(0);
    const indicOrArabic = (cp >= 0x0900 && cp <= 0x0d7f) || (cp >= 0x0600 && cp <= 0x06ff);
    return indicOrArabic && cp !== 0x0964 && cp !== 0x0965 && (cp < lo || cp > hi);
  });
};

let failed = false;
for (const [code, map] of Object.entries(maps)) {
  for (const [en, value] of Object.entries(map)) {
    const where = `${code} ${JSON.stringify(en.slice(0, 70))}`;
    if (!known.has(en)) { console.error('unknown key', where); failed = true; }
    if (typeof value !== 'string' || !value.trim()) { console.error('empty', where); failed = true; continue; }
    if (tokens(en) !== tokens(value)) { console.error('tokens', where); failed = true; }
    if (links(en) !== links(value)) { console.error('links', where); failed = true; }
    if (bold(en) !== bold(value)) { console.error('bold', where); failed = true; }
    if (foreignScript(code, value)) { console.error('mixed script', where); failed = true; }
    if (digits(en) !== digits(value)) console.warn('digits differ (check alignment)', where, '->', JSON.stringify(value.slice(0, 60)));
  }
}
if (failed) process.exit(1);

for (const [code, map] of Object.entries(maps)) {
  const lines = Object.entries(map).map(([en, value]) => `  ${JSON.stringify(en)}: ${JSON.stringify(value)},`);
  const header = '// Generated by scripts/emit-content-copy.mjs. Needs a native read before launch.\n';
  const body = lines.length ? `{\n${lines.join('\n')}\n}` : '{}';
  writeFileSync(new URL(`../src/lib/cms/copy/${code}.ts`, import.meta.url), `${header}export const ${code}: Record<string, string> = ${body};\n`);
  console.log(code, `${lines.length}/${keys.length}`);
}
