/**
 * The item bank in Hindi, keyed by item id.
 *
 * Kept apart from the English items for two reasons. A Hindi speaker can review
 * the whole translation in one file instead of hunting through seven, which is
 * the only way this gets checked by someone qualified to check it. And the
 * English items stay readable as the source of truth, so a translation can
 * never quietly become the definition of an item.
 *
 * **Options must stay in the English order.** `correct` indexes one array and
 * serves both languages, so reordering a translation moves the right answer
 * without anything failing. The shuffle that the candidate sees is applied
 * afterwards, to whichever language was served.
 *
 * The English section is deliberately absent. It is the one section where the
 * language is the construct, and translating it would measure nothing.
 *
 * Why this exists at all: the skills items were English-only, so a skilled cook
 * with weak English scored badly on cooking for a reason that has nothing to do
 * with cooking. That is construct-irrelevant variance, it is the single largest
 * threat to this test's validity, and in a product sold to Indian candidates it
 * is also the shape indirect discrimination takes.
 */

